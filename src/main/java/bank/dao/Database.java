package bank.dao;

import bank.exception.BankException;
import bank.model.Role;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;
//Opens connections to the H2 database and creates the 4 tables the first time
public class Database {
    // A file database: the data is still there when you close and reopen the program
    private static String url = "jdbc:h2:./bankdb";

    // Used by BankDemo and the tests: the data lives in memory and disappears when the program ends
    public static void useMemory() {
        url = "jdbc:h2:mem:bank;DB_CLOSE_DELAY=-1";
    }

    public static Connection getConnection() throws SQLException {
        return DriverManager.getConnection(url, "sa", "");
    }

    // Creates the tables if they do not exist yet, then adds the two starter staff logins
    public static void createTables() {
        try (Connection con = getConnection(); Statement st = con.createStatement()) {
            st.execute("CREATE TABLE IF NOT EXISTS users("
                    + "username VARCHAR(30) PRIMARY KEY, "
                    + "password VARCHAR(50) NOT NULL, "
                    + "role VARCHAR(10) NOT NULL)");

            st.execute("CREATE TABLE IF NOT EXISTS customers("
                    + "customer_id VARCHAR(10) PRIMARY KEY, "
                    + "customer_type VARCHAR(15) NOT NULL, "
                    + "first_name VARCHAR(50), "
                    + "surname VARCHAR(50), "
                    + "national_id VARCHAR(30), "
                    + "organisation_name VARCHAR(100), "
                    + "registration_number VARCHAR(30), "
                    + "contact_person VARCHAR(50), "
                    + "address VARCHAR(150), "
                    + "phone VARCHAR(20), "
                    + "email VARCHAR(100))");

            st.execute("CREATE TABLE IF NOT EXISTS accounts("
                    + "account_number VARCHAR(10) PRIMARY KEY, "
                    + "account_type VARCHAR(15) NOT NULL, "
                    + "customer_id VARCHAR(10) NOT NULL, "
                    + "branch VARCHAR(50), "
                    + "balance DOUBLE PRECISION NOT NULL, "
                    + "employer_name VARCHAR(100), "
                    + "employer_address VARCHAR(150), "
                    + "employer_contact VARCHAR(30), "
                    + "FOREIGN KEY (customer_id) REFERENCES customers(customer_id))");

            st.execute("CREATE TABLE IF NOT EXISTS transactions("
                    + "transaction_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "account_number VARCHAR(10) NOT NULL, "
                    + "tx_type VARCHAR(15) NOT NULL, "
                    + "amount DOUBLE PRECISION NOT NULL, "
                    + "note VARCHAR(100), "
                    + "created_at TIMESTAMP NOT NULL, "
                    + "FOREIGN KEY (account_number) REFERENCES accounts(account_number))");
        } catch (SQLException e) {
            throw new BankException("Could not create the tables: " + e.getMessage());
        }

        UserDAO users = new UserDAO();
        if (users.findByUsername("teller") == null) {
            users.insert("teller", "teller123", Role.TELLER);
        }
        if (users.findByUsername("manager") == null) {
            users.insert("manager", "manager123", Role.MANAGER);
        }
    }

    // Wipes everything and starts again (used by the tests)
    public static void reset() {
        try (Connection con = getConnection(); Statement st = con.createStatement()) {
            st.execute("DROP ALL OBJECTS");
        } catch (SQLException e) {
            throw new BankException("Could not reset the database: " + e.getMessage());
        }
        createTables();
    }
}

